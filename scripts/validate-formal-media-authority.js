const fs=require('fs');
const must=(ok,msg)=>{if(!ok)throw new Error(msg)};
const authority=JSON.parse(fs.readFileSync('formal-media-authority-v20260810.json','utf8'));
const master=JSON.parse(fs.readFileSync('line-sales-master.json','utf8'));
const safety=fs.readFileSync('line-image-safety.js','utf8');
const text=JSON.stringify(master);
const expected=['100g／罐','30cc／罐（小玻璃罐）','180cc／包（鋁袋）','75g／盒｜8塊裝','600g／盒｜32塊裝','75g／罐'];
for(const spec of expected) must(text.includes(spec),`LINE正式銷售母本缺少最新規格：${spec}`);
must(Object.keys(authority.source_product_dm||{}).length===6,'LINE必須有六項使用者核准DM來源');
for(const url of Object.values(authority.source_product_dm||{})) must(/^https:\/\/ts15825868\.github\.io\/xianjiawei\/images\/dm-approved-v20260810\/.+\.webp$/.test(url),`核准DM來源不正確：${url}`);
for(const url of Object.values(authority.product_dm||{})) must(/^https:\/\/ts-line\.onrender\.com\/assets\/formal-dm\/.+\.jpg\?v=/.test(url),`LINE顯示圖必須由正式JPEG轉換路由提供：${url}`);
must(/guilu-drink-trial\.webp$/.test(authority.source_trial||''),'試喝原始圖未指向最新使用者核准WebP');
must(/\/assets\/formal-dm\/trial\.jpg\?v=/.test(authority.trial||''),'LINE試喝顯示圖未指向正式JPEG路由');
must(safety.includes('resize({ width: 1024, height: 1024, fit: "inside"')&&safety.includes('jpeg({ quality: 88'),'LINE核准圖必須等比例縮小並轉JPEG');
must(safety.includes('officialOriginalImage: original')&&safety.includes('products-v3-remains-identity-authority'),'不得以DM取代products-v3產品本體識別權威');
must(authority.hard_rules.some(x=>x.includes('products-v3')),'不得放寬products-v3產品本體權威');
must(authority.guard_principle.includes('never fail only because'),'守門員必須驗正式能力，不得守舊版號／舊固定文案');
console.log('PASS：LINE正式規格、使用者核准DM／試喝圖、JPEG相容轉換與能力式守門已同步。');
